"""
Recommendations module business logic (SRS-FR-024–027).

Rule-based, advisory, human-reviewed, non-executing — per TRD v1.0
Section 17 and API Specification v1.0 Section 19. No routing, donor/
recipient matching, logistics, optimization, or external-partner logic
exists anywhere in this module.

=== PROPOSED IMPLEMENTATION DECISION: generation trigger point ===
Per API Specification v1.0 Section 19: "recommendations are generated by
the backend's recommendations module automatically when a period is
classified Surplus... not via an explicit frontend-initiated creation
action." No source document specifies the *exact* trigger point for
this automatic generation (no event-driven infrastructure exists in
this MVP — Kafka/message queues are explicitly excluded).

This implementation triggers recommendation recomputation as a side
effect of `POST /planned-quantities` and `PATCH /planned-quantities/{id}`
(see app/modules/planned_quantities/service.py) — i.e., whenever a
Planned Quantity is created or edited, the system immediately
recalculates that period's classification against whatever Forecasted
Demand currently exists, and generates/updates a recommendation if (and
only if) the period is now Surplus. This is deliberately NOT triggered
by the read-only `GET /comparisons` or `GET /classifications` endpoints,
to avoid a GET request having a side effect (state mutation).

This is a PROPOSED technical decision, not a confirmed requirement. Once
actual forecast generation (Phase 5) exists, it would be equally
reasonable to also trigger this from forecast generation — that is not
implemented here, since forecasting itself is out of scope for Phase 4.

=== Idempotency ===
`ensure_recommendation_for_period` is idempotent: calling it repeatedly
for the same period updates the existing recommendation row (if one
exists) rather than creating duplicates. If a period was previously
Surplus (and has a stored recommendation) but is no longer Surplus, the
existing recommendation is left as-is (a historical record of when it
was generated) — it is not deleted or overwritten. Whether stale
recommendations should be retired is a business-rule decision not
specified by any source document, so no such logic is invented here.
"""

import uuid
from datetime import date as date_type

from sqlalchemy.orm import Session

from app.core.errors import NotFoundError
from app.modules.classification.service import get_classification_for_period
from app.modules.locations.models import Location
from app.modules.meal_types.models import MealType
from app.modules.recommendations.models import RedistributionRecommendation


def _build_recommendation_text(
    location_name: str, meal_type_name: str, period_date: date_type, estimated_surplus: float
) -> str:
    """
    Simple, rule-based advisory text. No secondary-location suggestion
    logic exists (no configuration for "approved secondary locations"
    is defined by any source document), so `secondaryLocationId` is
    always left unset by this implementation — see
    ensure_recommendation_for_period.
    """
    return (
        f"Potential surplus of {estimated_surplus:g} meals for {meal_type_name} "
        f"at {location_name} on {period_date.isoformat()}. Consider reducing the "
        f"next preparation batch and reviewing options for redirecting the "
        f"available surplus."
    )


def ensure_recommendation_for_period(
    db: Session, location_id: uuid.UUID, meal_type_id: uuid.UUID, period_date: date_type
) -> RedistributionRecommendation | None:
    """
    Recomputes classification for the given period and, if (and only
    if) it is currently Surplus, creates or updates the corresponding
    recommendation. Returns the recommendation if one now exists for a
    Surplus period, otherwise None (including when the period is not
    Surplus).
    """
    classification = get_classification_for_period(db, location_id, meal_type_id, period_date)
    if classification.status != "surplus":
        return None

    estimated_surplus = classification.comparison.potential_surplus
    if estimated_surplus is None:
        return None  # Defensive: should not happen if status == "surplus".

    location = db.get(Location, location_id)
    meal_type = db.get(MealType, meal_type_id)
    location_name = location.name if location else str(location_id)
    meal_type_name = meal_type.name if meal_type else str(meal_type_id)

    text = _build_recommendation_text(location_name, meal_type_name, period_date, estimated_surplus)

    existing = (
        db.query(RedistributionRecommendation)
        .filter_by(period_date=period_date, location_id=location_id, meal_type_id=meal_type_id)
        .one_or_none()
    )
    if existing is not None:
        existing.estimated_surplus_quantity = estimated_surplus
        existing.recommendation_text = text
        db.commit()
        db.refresh(existing)
        return existing

    recommendation = RedistributionRecommendation(
        period_date=period_date,
        location_id=location_id,
        meal_type_id=meal_type_id,
        estimated_surplus_quantity=estimated_surplus,
        recommendation_text=text,
        secondary_location_id=None,
        is_advisory=True,
    )
    db.add(recommendation)
    db.commit()
    db.refresh(recommendation)
    return recommendation


def list_recommendations(
    db: Session,
    page: int,
    page_size: int,
    location_id: uuid.UUID | None = None,
    meal_type_id: uuid.UUID | None = None,
    date_from: date_type | None = None,
    date_to: date_type | None = None,
) -> tuple[list[RedistributionRecommendation], int]:
    query = db.query(RedistributionRecommendation)
    if location_id is not None:
        query = query.filter(RedistributionRecommendation.location_id == location_id)
    if meal_type_id is not None:
        query = query.filter(RedistributionRecommendation.meal_type_id == meal_type_id)
    if date_from is not None:
        query = query.filter(RedistributionRecommendation.period_date >= date_from)
    if date_to is not None:
        query = query.filter(RedistributionRecommendation.period_date <= date_to)

    total_items = query.count()
    recommendations = (
        query.order_by(RedistributionRecommendation.generated_at.desc())
        .offset((page - 1) * page_size)
        .limit(page_size)
        .all()
    )
    return recommendations, total_items


def get_recommendation(db: Session, recommendation_id: uuid.UUID) -> RedistributionRecommendation:
    recommendation = db.get(RedistributionRecommendation, recommendation_id)
    if recommendation is None:
        raise NotFoundError(f"Recommendation '{recommendation_id}' not found.")
    return recommendation
