"""
Forecasting algorithms (ML & Testing Plan v1.0 Section 6).

Per ML & Testing Plan v1.0 Section 6.1, only a small number of candidate
*categories* are considered, framed abstractly (no algorithm was
pre-selected by any planning document). This module implements exactly
two, evaluated against each other in evaluation.py:

1. `recent_period_mean` — a **statistical baseline** (Section 6.1's
   first category): the mean of the most recent `window` historical
   observations for the (location, meal type). Simple, explainable,
   appropriate when no trend or seasonality is expected.

2. `day_of_week_seasonal_mean` — a **time-series-specific** approach
   (Section 6.1's third category): the mean of historical observations
   falling on the same weekday as the target date (a seasonal-naive
   style method), falling back to `recent_period_mean` if too few
   same-weekday observations exist to be meaningful.

=== SELECTED MODEL: `recent_period_mean` (the baseline) ===
Per the evaluation in `evaluation.py` (see also
docs/phase-5-verification.md's model-selection results), run against
the synthetic demo dataset reproducibly generated by
`backend/scripts/seed_demo_data.py` (RNG seed 42): the day-of-week
candidate did NOT outperform the simple baseline — aggregate MAE was
16.50 (baseline) vs 17.89 (candidate), and MAPE 8.65% vs 9.38%,
consistent with the synthetic data having no deliberately-built
day-of-week pattern (`seed_demo_data.py` applies uniform +/-15% noise
around a constant per-meal-type base, with no weekday-specific
multiplier).

Per ML & Testing Plan v1.0 Section 6.3, step 6 ("select the candidate
that performs best against the baseline while remaining simple and
explainable — a marginal accuracy gain from a substantially more
complex approach is not automatically preferred"): since the baseline
both won on accuracy AND is the simpler approach, it is the selected
production model. This is an evidence-based outcome, not a default —
`day_of_week_seasonal_mean` remains implemented and tested (see
tests/test_forecasting.py) so the comparison can be reproduced or
re-run once real (non-synthetic) data is available, per this module's
explicit non-finality.

=== What remains explicitly open ===
- The window size (14) is a parameter, not a business decision —
  configurable via `FORECAST_RECENT_WINDOW_SIZE` (app/config.py).
- This selection is based on ONE synthetic dataset. Real operational
  data (still unconfirmed as available — every prior planning document)
  could show different characteristics; re-evaluation is expected once
  real data exists (ML & Testing Plan v1.0 Section 7.1 — no permanent
  accuracy claim is made).
- No hyperparameter search, ensembling, or advanced modeling was
  performed — consistent with the internship-scale, explainability-
  first guardrails (Foundation v1.1; ML & Testing Plan v1.0 Section 2).
"""

import statistics
from datetime import date as date_type

MIN_SAME_WEEKDAY_SAMPLE = 3


def recent_period_mean(history: list[tuple[date_type, float]], window: int) -> float:
    """
    Baseline / SELECTED PRODUCTION MODEL: mean of the most recent
    `window` observations (or all available observations, if fewer than
    `window` exist).

    Callers are responsible for ensuring `history` is non-empty (see
    app/modules/forecasting/service.py's insufficient-data check) —
    this function does not itself decide data sufficiency.
    """
    recent = history[-window:] if len(history) >= window else history
    return statistics.mean(quantity for _, quantity in recent)


def day_of_week_seasonal_mean(
    history: list[tuple[date_type, float]], target_date: date_type, fallback_window: int
) -> float:
    """
    Candidate (evaluated, NOT selected — see module docstring): mean of
    historical observations that fall on the same weekday as
    `target_date`. Falls back to `recent_period_mean` if fewer than
    `MIN_SAME_WEEKDAY_SAMPLE` same-weekday observations exist.
    """
    same_weekday_quantities = [
        quantity for record_date, quantity in history if record_date.weekday() == target_date.weekday()
    ]
    if len(same_weekday_quantities) >= MIN_SAME_WEEKDAY_SAMPLE:
        return statistics.mean(same_weekday_quantities)
    return recent_period_mean(history, fallback_window)
